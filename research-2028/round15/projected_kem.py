"""Round 15 single-recipient differential KEM with projected sparse noise.

Uses the Round 14 decoding experiments at their original dimensions. The
public matrix is regenerated by row. This variable-time research reference
runs on small fixtures; the three large profiles are size descriptors.
"""
from functools import cached_property
from hmac import compare_digest
from math import comb
from pathlib import Path
import secrets
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "round14"))
from differential_kem import _hash
from differential_pke import (Params, _pack_dense, _unpack_dense, _signed_subset,
                              _UnusedPositions, _width, packed_width)
from parameters import illustration, support_bytes
from concatenated import ConcatenatedOuter, concat_shape


_MATRIX = b"SG-DIFRA/R15/matrix-row/v1"
_PRIVATE = b"SG-DIFRA/R15/private-supports/v1"
_COINS = b"SG-DIFRA/R15/FO/G/v1"
_KEY = b"SG-DIFRA/R15/FO/H/v1"
_SUITE = b"SG-DIFRA/R15/projected-Golay-RS/64-row/v1"
_SEED_BYTES = 32
_ROWS_PER_BLOCK = 64


class ProjectedKEM:
    """Keygen returns (public, private), encaps returns (ciphertext, key)."""

    key_bytes = 32

    def __init__(self, source, nonce_bytes=32):
        if not isinstance(source, Params):
            raise TypeError("source must identify a Round 14 parameter distribution")
        if type(nonce_bytes) is not int or not 1 <= nonce_bytes < 2**64:
            raise ValueError("nonce width must be a positive uint64")
        if source.d > 2**64:
            raise ValueError("matrix rows exceed the uint64 row address space")
        self.source = source
        self.t = concat_shape(source.bits, source.z)[3]
        if self.t > source.t:
            raise ValueError("outer code requires more check coordinates than the source")
        self.m = source.m - (source.t-self.t)*source.w
        self.N = self.m + self.t
        self.nonce_bytes = nonce_bytes
        self.seed_bytes = source.message_bytes
        self.slack = source.bits + 64
        self.slack_bytes = (self.slack + 7)//8
        config = (source.bits, source.h, source.n, source.m, source.w, source.z,
                  source.slack, nonce_bytes, self.m, self.t)
        self.suite = (_SUITE + b"".join(v.to_bytes(8, "big") for v in config)
                      + source.outer.encode("ascii"))
        complete, tail = divmod(source.d, _ROWS_PER_BLOCK)
        self.public_bytes = _SEED_BYTES + complete * packed_width(_ROWS_PER_BLOCK*self.t)
        if tail:
            self.public_bytes += packed_width(tail*self.t)
        self.private_bytes = _SEED_BYTES + self.seed_bytes
        self.body_bytes = packed_width(self.N)
        self.ciphertext_bytes = nonce_bytes + self.body_bytes

    @cached_property
    def _outer(self):
        return ConcatenatedOuter(self.source.bits, self.source.z)

    @cached_property
    def _row_count(self):
        return 3**self.m

    def _row(self, seed, i):
        width = packed_width(self.m)
        raw = _hash(_MATRIX, self.suite, seed, i.to_bytes(8, "big"), width+self.slack_bytes)
        rank = int.from_bytes(raw, "big") % self._row_count
        return _unpack_dense(rank.to_bytes(width, "big"), self.m)

    def _checks(self, private_seed):
        p = self.source
        length = support_bytes(self.m, p.w, self.t) + self.t*self.slack_bytes
        tape = _hash(_PRIVATE, self.suite, b"", private_seed, length)
        available = _UnusedPositions(self.m)
        checks = []
        start = 0
        for j in range(self.t):
            remaining = self.m - j*p.w
            count = comb(remaining, p.w) << p.w
            end = start + _width(count) + self.slack_bytes
            rank = int.from_bytes(tape[start:end], "big") % count
            start = end
            signed = tuple((available.select(pos), sign)
                           for pos, sign in _signed_subset(remaining, p.w, rank))
            for pos, _ in signed:
                available.remove(pos)
            checks.append(signed)
        return checks

    def _blocks(self):
        for i in range(0, self.source.d, _ROWS_PER_BLOCK):
            yield i, min(self.source.d-i, _ROWS_PER_BLOCK)

    def _public(self, seed, checks):
        public = bytearray(seed)
        for first, count in self._blocks():
            syndromes = bytearray()
            for i in range(first, first+count):
                row = self._row(seed, i)
                syndromes.extend(sum(row[pos]*sign for pos, sign in check) % 3
                                 for check in checks)
            public.extend(_pack_dense(syndromes))
        return bytes(public)

    def keygen(self):
        seed = secrets.token_bytes(_SEED_BYTES)
        private_seed = secrets.token_bytes(self.seed_bytes)
        return self._public(seed, self._checks(private_seed)), seed+private_seed

    def _body(self, public, message, coins):
        p = self.source
        if type(message) is not bytes or len(message) != p.message_bytes:
            raise ValueError("noncanonical message")
        integer = int.from_bytes(message, "big")
        if integer >= 1 << p.bits:
            raise ValueError("noncanonical message")
        if type(coins) is not bytes or len(coins) != p.coin_bytes:
            raise ValueError("invalid sender coin width")
        # Full-length noise has the Round 14 law before its public projection.
        rank = int.from_bytes(coins, "big") % p.coin_count
        inputs, noise = divmod(rank, p.noise_count)
        width = packed_width(p.h+p.n)
        variables = _unpack_dense(inputs.to_bytes(width, "big"), p.h+p.n)
        x = variables[p.h:]
        features = list(variables[:p.h])
        features.extend(a*x[j] % 3 for i, a in enumerate(x) for j in range(i, p.n))
        body = [0]*self.m + list(self._outer.encode(integer))
        offset = _SEED_BYTES
        for first, count in self._blocks():
            end = offset + packed_width(count*self.t)
            syndromes = _unpack_dense(public[offset:end], count*self.t)
            offset = end
            for j in range(count):
                value = features[first+j]
                if value:
                    for k, a in enumerate(self._row(public[:_SEED_BYTES], first+j)):
                        body[k] += value*a
                    begin = j*self.t
                    for k in range(self.t):
                        body[self.m+k] += value*syndromes[begin+k]
        for pos, sign in _signed_subset(p.N, p.z, noise):
            if pos < self.N:
                body[pos] += sign
        return _pack_dense([v % 3 for v in body])

    def _ciphertext(self, public, message):
        tape = _hash(_COINS, self.suite, public, message,
                     self.nonce_bytes+self.source.coin_bytes)
        return tape[:self.nonce_bytes] + self._body(public, message, tape[self.nonce_bytes:])

    def encaps(self, public):
        if type(public) is not bytes or len(public) != self.public_bytes:
            raise ValueError("invalid encapsulation-key width or type")
        p = self.source
        message = secrets.randbits(p.bits).to_bytes(p.message_bytes, "big")
        return self._ciphertext(public, message), _hash(_KEY, self.suite, public, message, self.key_bytes)

    def decaps(self, private, ciphertext):
        if type(private) is not bytes or len(private) != self.private_bytes:
            raise ValueError("invalid private key")
        if type(ciphertext) is not bytes or len(ciphertext) != self.ciphertext_bytes:
            return None
        try:
            word = _unpack_dense(ciphertext[self.nonce_bytes:], self.N)
        except ValueError:
            return None
        checks = self._checks(private[_SEED_BYTES:])
        residual = [(word[self.m+j] - sum(sign*word[pos] for pos,sign in check)) % 3
                    for j,check in enumerate(checks)]
        integer = self._outer.decode(residual)
        if integer is None:
            return None
        message = integer.to_bytes(self.source.message_bytes, "big")
        public = self._public(private[:_SEED_BYTES], checks)
        if not compare_digest(ciphertext, self._ciphertext(public, message)):
            return None
        return _hash(_KEY, self.suite, public, message, self.key_bytes)


def research_profile(target):
    """Construct the profile descriptor and report sizes without expanding a matrix."""
    if type(target) is not int or target not in (128, 192, 256):
        raise ValueError("expected a 128, 192 or 256 research target")
    layout = illustration(target)
    source = Params(layout.bits, layout.h, layout.n, layout.m, layout.w,
                    layout.z, layout.slack, outer="rs")
    return ProjectedKEM(source, nonce_bytes=layout.nonce_bytes)
